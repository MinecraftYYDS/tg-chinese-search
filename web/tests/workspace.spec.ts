import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

test('setup, navigation, API configuration, mobile layout and logout', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '创建你的内容工作台' })).toBeVisible()
  const bootstrap = readFileSync(resolve(process.env.TG_E2E_DATA!, 'bootstrap-token.txt'), 'utf8').trim()
  await page.getByLabel('一次性初始化凭据').fill(bootstrap)
  await page.getByLabel('管理员用户名').fill('e2eadmin')
  await page.getByLabel('管理员密码', { exact: true }).fill('e2e-long-password-123')
  await page.getByRole('button', { name: '创建管理员 →' }).click()
  await expect(page.getByRole('heading', { name: '概览', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('desktop.png'), fullPage: true })
  await page.getByRole('button', { name: /频道管理 CHANNELS/ }).click()
  await expect(page.getByRole('heading', { name: '添加指定频道' })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加并同步 →' })).toBeDisabled()
  await page.getByRole('button', { name: /Telegram 账号 ACCOUNT/ }).click()
  await expect(page.getByRole('button', { name: '生成登录二维码' })).toBeDisabled()
  await page.getByRole('button', { name: /内容搜索 LIBRARY/ }).click()
  await expect(page.getByRole('heading', { name: '暂时没有找到内容' })).toBeVisible()
  await page.getByRole('button', { name: /服务设置 SETTINGS/ }).click()
  await page.getByLabel('启用搜索 / 随机接口').check()
  await page.getByRole('button', { name: '保存服务设置' }).click()
  await expect(page.getByRole('status')).toContainText('设置已保存')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '生成 / 重置 API Token' }).click()
  await expect(page.locator('.token-box code')).toBeVisible()
  const token = await page.locator('.token-box code').innerText()
  const response = await page.request.get('/api/random', { headers: { Authorization: `Bearer ${token}` } })
  expect(response.status()).toBe(200)
  expect((await response.json()).data.items).toEqual([])
  await page.getByRole('button', { name: /操作记录 ACTIVITY/ }).click()
  await expect(page.getByText('api_token_rotate', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('nav button').filter({ hasText: '概览' }).click()
  await expect(page.getByRole('heading', { name: '概览', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录管理后台' })).toBeVisible()
  await page.getByLabel('管理员用户名').fill('e2eadmin')
  await page.getByLabel('管理员密码', { exact: true }).fill('e2e-long-password-123')
  await page.getByRole('button', { name: '登录工作台 →' }).click()
  await expect(page.getByRole('heading', { name: '概览', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
